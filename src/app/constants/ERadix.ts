/**
 * Supported numeric bases (radices) for input parsing and output formatting.
 *
 * Values correspond to the mathematical base (e.g., `Binary = 2`, `Hex = 16`).
 */
export enum ERadix {
	Binary = 2,
	Octal = 8,
	Decimal = 10,
	Duodecimal = 12,
	Hexadecimal = 16,
	Vigesimal = 20,
	Sexagesimal = 60,
}
